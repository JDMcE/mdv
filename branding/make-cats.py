"""Split branding/cats.svg into one icon per cat for the settings button.

Run from the repo root:  python branding/make-cats.py
Writes web/src/cats.ts. Every filled <path> in the OBJECTS group is one cat.
"""
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "branding/cats.svg"
out = sys.argv[2] if len(sys.argv) > 2 else "web/src/cats.ts"
svg = open(src, encoding="utf8").read()
objects = svg[svg.index('id="OBJECTS"'):]
paths = [re.sub(r"\s+", "", d) for d in re.findall(r'<path[^>]*?\sd="([^"]+)"', objects, re.S)]

NUM = re.compile(r"-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?")
TOK = re.compile(r"[MmLlHhVvCcSsQqTtZz]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?")
ARGS = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6, "S": 4, "Q": 4, "T": 2, "Z": 0}


def bbox(d: str):
    """Bounds of a path without arcs, sampling the curves."""
    toks = TOK.findall(d)
    xs, ys = [], []
    x = y = sx = sy = 0.0
    cx = cy = None  # last control point, for S/T
    i, cmd = 0, None
    while i < len(toks):
        if toks[i].isalpha():
            cmd = toks[i]
            i += 1
            if cmd in "Zz":
                x, y = sx, sy
                cx = cy = None
                continue
        n = ARGS[cmd.upper()]
        a = [float(v) for v in toks[i:i + n]]
        i += n
        rel = cmd.islower()
        ox, oy = (x, y) if rel else (0.0, 0.0)
        C = cmd.upper()
        pts = []
        if C in "ML":
            x, y = ox + a[0], oy + a[1]
            if C == "M":
                sx, sy = x, y
                cmd = "l" if rel else "L"  # extra pairs after M are lines
            cx = cy = None
        elif C == "H":
            x = ox + a[0] if rel else a[0]
            cx = cy = None
        elif C == "V":
            y = oy + a[0] if rel else a[0]
            cx = cy = None
        elif C in "CS":
            if C == "C":
                c1 = (ox + a[0], oy + a[1])
                c2, e = (ox + a[2], oy + a[3]), (ox + a[4], oy + a[5])
            else:
                c1 = (2 * x - cx, 2 * y - cy) if cx is not None else (x, y)
                c2, e = (ox + a[0], oy + a[1]), (ox + a[2], oy + a[3])
            for k in range(1, 9):
                t = k / 8
                mt = 1 - t
                pts.append((
                    mt**3 * x + 3 * mt * mt * t * c1[0] + 3 * mt * t * t * c2[0] + t**3 * e[0],
                    mt**3 * y + 3 * mt * mt * t * c1[1] + 3 * mt * t * t * c2[1] + t**3 * e[1],
                ))
            cx, cy = c2
            x, y = e
        elif C in "QT":
            q = (ox + a[0], oy + a[1]) if C == "Q" else ((2 * x - cx, 2 * y - cy) if cx is not None else (x, y))
            e = (ox + a[2], oy + a[3]) if C == "Q" else (ox + a[0], oy + a[1])
            for k in range(1, 9):
                t = k / 8
                mt = 1 - t
                pts.append((mt * mt * x + 2 * mt * t * q[0] + t * t * e[0], mt * mt * y + 2 * mt * t * q[1] + t * t * e[1]))
            cx, cy = q
            x, y = e
        pts.append((x, y))
        for px, py in pts:
            xs.append(px)
            ys.append(py)
    return min(xs), min(ys), max(xs), max(ys)


def short(d: str) -> str:
    # 2 decimals is far below a pixel at icon size; trims the bundle.
    return NUM.sub(lambda m: f"{float(m.group()):.2f}".rstrip("0").rstrip(".").replace("-0.", "-.").lstrip("0") or "0"
                   if "." in m.group() else m.group(), d)


cats = []
for d in paths:
    x0, y0, x1, y1 = bbox(d)
    w, h = x1 - x0, y1 - y0
    pad = max(w, h) * 0.02  # tight box; the button sizes it by height
    cats.append((f"{x0 - pad:.1f} {y0 - pad:.1f} {w + 2 * pad:.1f} {h + 2 * pad:.1f}", short(d)))

with open(out, "w", encoding="utf8", newline="\n") as f:
    f.write("// Generated by branding/make-cats.py from branding/cats.svg. Don't edit by hand.\n\n")
    f.write("/** Cat silhouettes: a square viewBox and a filled (even-odd) path for each. */\n")
    f.write("export const CATS: { viewBox: string; d: string }[] = [\n")
    for vb, d in cats:
        f.write(f'  {{ viewBox: "{vb}", d: "{d}" }},\n')
    f.write("];\n")
print(f"{len(cats)} cats -> {out}")
for vb, _ in cats:
    print(" ", vb)
